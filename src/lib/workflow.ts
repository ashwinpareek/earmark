/** PayPal webhooks are the source of truth for the ledger: a movement shows as confirmed only
 *  when PayPal says so (signature-verified upstream in /api/paypal/webhook). */
export async function onWebhook(event: { event_type: string; resource: Record<string, unknown> }) {
  const r = event.resource as { id?: string; status?: string; payout_batch_id?: string; transaction_status?: string; payout_item?: { sender_item_id?: string }; supplementary_data?: { related_ids?: { authorization_id?: string } } };
  const t = event.event_type;
  let n = 0;
  if (t === "PAYMENT.AUTHORIZATION.CREATED") n = await confirmMovements((m) => m.type === "hold" && m.paypalId === r.id, "webhook");
  else if (t === "PAYMENT.AUTHORIZATION.VOIDED") n = await confirmMovements((m) => m.type === "void" && m.paypalId === r.id, "webhook", "VOIDED");
  else if (t === "PAYMENT.CAPTURE.COMPLETED") {
    n = await confirmMovements((m) => m.type === "capture" && m.paypalId === r.id, "webhook", "COMPLETED");
    // final_capture released the rest of that hold at the same moment
    const auth = r.supplementary_data?.related_ids?.authorization_id;
    if (auth) n += await confirmMovements((m) => m.type === "void" && m.paypalId === auth && !m.confirmed, "webhook", "RELEASED");
  } else if (t === "PAYMENT.CAPTURE.DENIED" || t === "PAYMENT.CAPTURE.DECLINED") n = await confirmMovements((m) => m.type === "capture" && m.paypalId === r.id, "webhook", "DENIED");
  else if (t.startsWith("PAYMENT.PAYOUTS-ITEM.")) {
    const ref = r.payout_item?.sender_item_id;
    n = await confirmMovements((m) => m.type === "payout" && m.paypalId === r.payout_batch_id && (!ref || m.ref === ref), "webhook", (r.transaction_status ?? t.split(".").pop())!.toUpperCase());
  }
  return n ? `confirmed ${n}` : "no matching movement";
}

/** Read every unconfirmed movement back from the PayPal API (for local runs without a
 *  public webhook URL, or if a webhook was missed). */
export async function syncWithPayPal(id: string) {
  const c = await getCampaign(id);
  if (!c) throw new HttpError(404, "Campaign not found");
  const results: { id: string; status: string }[] = [];
  const batches = new Map<string, Awaited<ReturnType<typeof paypal.getPayoutBatch>>>();
  for (const m of c.movements.filter((x) => !x.confirmed || x.confirmed.via === "mock")) {
    try {
      if (m.type === "capture") results.push({ id: m.id, status: (await paypal.getCapture(m.paypalId)).status });
      else if (m.type === "hold" || m.type === "void") {
        const d = c.donations.find((x) => x.id === m.donationId);
        results.push({ id: m.id, status: (await paypal.getAuthorization(m.paypalId, d?.authorizationExpiresAt)).status });
      } else if (m.type === "payout") {
        if (!batches.has(m.paypalId)) batches.set(m.paypalId, await paypal.getPayoutBatch(m.paypalId));
        const b = batches.get(m.paypalId)!;
        results.push({ id: m.id, status: b.items.find((i) => i.ref === m.ref)?.status ?? b.status });
      }
    } catch {
      /* leave unconfirmed */
    }
  }
  const OK: Record<string, string[]> = {
    hold: ["CREATED", "CAPTURED", "PARTIALLY_CAPTURED", "VOIDED"],
    capture: ["COMPLETED"],
    void: ["VOIDED", "CAPTURED", "PARTIALLY_CAPTURED"],
    payout: ["SUCCESS", "UNCLAIMED", "PENDING"],
  };
  return updateCampaign(id, (cc) => {
    let n = 0;
    for (const r of results) {
      const m = cc.movements.find((x) => x.id === r.id)!;
      if (OK[m.type].includes(r.status) && !(m.type === "payout" && r.status === "PENDING")) {
        m.confirmed = { at: nowIso(), via: "api", status: r.status };
        n++;
      }
      if (m.type === "payout") m.status = r.status;
    }
    addEvent(cc, { actor: "paypal", kind: "sync", message: `Checked ${results.length} money movements with PayPal; ${n} confirmed.` });
    return cc;
  });
}

/** Reuse radar: every document seen in more than one campaign, with where it went. */
export async function reuseRadar(space: string) {
  const fps = await fingerprints(space);
  const camps = new Map((await listCampaigns([space])).map((c) => [c.id, c]));
  const groups = new Map<string, typeof fps>();
  const pics: { phash: string; key: string; patientKey?: string }[] = [];
  // Same rule as the "Documents not reused" check: two patients' pages printed on one hospital's
  // form look alike, so a look-alike only counts as a copy when it's about the same patient
  // (or the patient can't be read).
  const samePatient = (a?: string, b?: string) => !a || !b || a === b;
  for (const f of fps) {
    const keys = [`sha:${f.sha256}`, ...(f.fingerprint ? [`fp:${f.fingerprint}`] : [])];
    if (f.phash) {
      // Re-saved copies join the group of the page they look like.
      const near = pics.find((p) => looksAlike(p.phash, f.phash) && samePatient(p.patientKey, f.patientKey));
      keys.push(near?.key ?? `pic:${f.docId}`);
      if (!near) pics.push({ phash: f.phash, key: `pic:${f.docId}`, patientKey: f.patientKey });
    }
    const existing = keys.map((k) => groups.get(k)).find(Boolean);
    const g = existing ?? [];
    if (!g.some((x) => x.docId === f.docId)) g.push(f);
    for (const k of keys) groups.set(k, g);
  }
  const seen = new Set<unknown>();
  const out = [];
  for (const g of groups.values()) {
    if (seen.has(g)) continue;
    seen.add(g);
    const ids = [...new Set(g.map((x) => x.campaignId))];
    if (ids.length < 2) continue;
    const sorted = [...g].sort((a, b) => a.at.localeCompare(b.at));
    const first = sorted[0];
    out.push({
      document: { kind: first.docKind, number: first.docNumber, issuer: first.issuer },
      original: { campaignId: first.campaignId, label: first.campaignLabel, status: camps.get(first.campaignId)?.status ?? "unknown", at: first.at },
      copies: ids.filter((x) => x !== first.campaignId).map((cid) => {
        const f = sorted.find((x) => x.campaignId === cid)!;
        return { campaignId: cid, label: f.campaignLabel, status: camps.get(cid)?.status ?? "unknown", at: f.at, sameFile: f.sha256 === first.sha256, samePicture: f.sha256 !== first.sha256 && looksAlike(f.phash, first.phash) && samePatient(f.patientKey, first.patientKey) };
      }),
    });
  }
  return out.sort((a, b) => (b.copies.at(-1)?.at ?? "").localeCompare(a.copies.at(-1)?.at ?? ""));
}

// ─── Hold monitor (daily) ─────────────────────────────────────────
// A PayPal authorization is honoured for 3 days and lives for 29. Once a day this renews holds
// that are past the honor period (PayPal only allows that from day 4), and marks holds that
// can no longer be collected, so the campaign page and the settlement step tell the truth.

const DAY = 864e5;
export const HONOR_DAYS = 3;
export const HOLD_DAYS = 29;

export async function monitorHolds(now = new Date()) {
  const report = { checked: 0, renewed: 0, lapsed: 0, renewFailed: 0 };
  for (const c of await listCampaigns()) {
    if (!["live", "bill_review", "bill_needs_review"].includes(c.status)) continue;
    for (const d of c.donations.filter((x) => x.status === "held" && x.authorizationId)) {
      report.checked++;
      const age = (now.getTime() - Date.parse(d.authorizedAt ?? d.createdAt)) / DAY;
      const expired = age >= HOLD_DAYS || (d.authorizationExpiresAt && Date.parse(d.authorizationExpiresAt) <= now.getTime());
      let usable = !expired;
      if (usable) {
        try { usable = (await paypal.getAuthorization(d.authorizationId!, d.authorizationExpiresAt)).usable; } catch { /* keep: settlement re-checks */ }
      }
      if (!usable) {
        report.lapsed++;
        await updateCampaign(c.id, (cc) => {
          const x = cc.donations.find((y) => y.id === d.id)!;
          x.status = "lapsed";
          x.problem = "the PayPal hold expired before the bill arrived";
          x.captured = "0.00";
          x.neverCharged = x.pledged;
          addEvent(cc, { actor: "paypal", kind: "hold.lapsed", message: `A ${fmtMoney(x.pledged, cc.currency)} pledge's PayPal hold expired before the hospital's bill arrived. The donor was never charged and can pledge again.` });
        });
        continue;
      }
      if (age > HONOR_DAYS && !d.reauthorizedAt) {
        try {
          const r = await paypal.reauthorize(d.authorizationId!, d.pledged, c.currency);
          report.renewed++;
          await updateCampaign(c.id, (cc) => {
            const x = cc.donations.find((y) => y.id === d.id)!;
            const old = x.authorizationId!;
            x.authorizationId = r.authorizationId;
            x.reauthorizedAt = now.toISOString();
            if (r.expiresAt) x.authorizationExpiresAt = r.expiresAt;
            cc.movements.push({ id: uid("mv"), type: "hold", amount: x.pledged, currency: cc.currency, paypalId: r.authorizationId, status: r.status, donationId: x.id, at: nowIso(), note: `Hold renewed after PayPal's 3-day honor period (replaces ${old})` });
            addEvent(cc, { actor: "paypal", kind: "hold.renewed", message: `Renewed a ${fmtMoney(x.pledged, cc.currency)} PayPal hold after its 3-day honor period, so it can still be collected when the bill arrives. Still not charged.` });
          });
        } catch (e) {
          report.renewFailed++;
          await updateCampaign(c.id, (cc) => {
            const x = cc.donations.find((y) => y.id === d.id)!;
            x.problem = `couldn't renew the hold: ${(e as Error).message.slice(0, 120)}`;
          });
        }
      }
    }
  }
  return report;
}

