// The campaign state machine. Every transition is guarded and written to the campaign
// timeline; every money movement is recorded with its PayPal ID for the public ledger.

// Pledges close at the verified goal plus a 10% buffer (holds can lapse or be declined). Late
// donors are pointed to the next verified patient instead, so surplus mostly never forms.
const MAX_OVERPLEDGE = GOAL_BUFFER;

function needProvider(id: string) {
  const p = getProvider(id);
  if (!p) throw new HttpError(400, "Choose a provider from the verified list");
  return p;
}

function expect(c: Campaign, ...ok: Campaign["status"][]) {
  if (!ok.includes(c.status)) throw new HttpError(409, `Campaign is ${c.status.replace(/_/g, " ")}; this action needs ${ok.join(" or ").replace(/_/g, " ")}`);
}

const labelFor = (c: Pick<Campaign, "title" | "patient">) => `${c.title} (${c.patient.displayName})`;

async function priorDocs(space: string): Promise<PriorDoc[]> {
  return (await fingerprints(space)).map((f) => ({ campaignId: f.campaignId, docId: f.docId, sha256: f.sha256, fingerprint: f.fingerprint, phash: f.phash, patientKey: f.patientKey, campaignLabel: f.campaignLabel }));
}

async function remember(c: Campaign, docs: Doc[]) {
  await addFingerprints(
    docs.filter((d) => d.extraction).map((d) => ({
      campaignId: c.id, docId: d.id, sha256: d.sha256, phash: d.phash, fingerprint: fingerprintOf(d.extraction!), patientKey: patientKey(d.extraction!.patientName),
      campaignLabel: labelFor(c), docKind: d.kind, docNumber: d.extraction!.documentNumber, issuer: d.extraction!.providerName, space: spaceOf(c),
    })),
  );
}

/** When a campaign's documents show up in another campaign, tell the original family. */
async function alertOriginals(from: Campaign, refs: { campaignId: string }[]) {
  for (const r of refs) {
    await updateCampaign(r.campaignId, (o) => {
      // Only alert genuine originals — never a campaign that was itself caught reusing documents.
      if (o.verification?.checks.some((k) => k.id === "duplicate" && k.status === "fail")) return;
      o.protectedCopies = (o.protectedCopies ?? 0) + 1;
      addEvent(o, { actor: "system", kind: "reuse.blocked", message: `Earmark caught a copy of documents from this campaign being used in another campaign. It was held for review; no donor can be charged for it.` });
    }).catch(() => undefined);
  }
}

async function ingest(kind: DocKind, filename: string, buf: Buffer, uploadedBy: Doc["uploadedBy"]): Promise<Doc> {
  const stored = await storeFile(buf);
  const phash = await visualHash(buf, stored.mime);
  return { id: uid("doc"), kind, filename: filename.slice(0, 120) || `${kind}`, mime: stored.mime, sha256: stored.sha256, size: stored.size, uploadedAt: nowIso(), uploadedBy, ...(phash ? { phash } : {}) };
}

// Forgery Lab: what the visitor edited, used only if the AI can't read the image (see lab.ts).
const labFallbacks = new Map<string, Extraction>();

async function read(doc: Doc): Promise<Doc> {
  const buf = await readFile(doc.sha256, doc.mime);
  const fallback = labFallbacks.get(doc.id);
  labFallbacks.delete(doc.id);
  const { extraction, model } = await readDocument(doc, buf, { fallback });
  return { ...doc, extraction, readerModel: model };
}

export function displayName(full: string) {
  const parts = full.trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return "The patient";
  return parts.length === 1 ? parts[0] : `${parts[0]} ${parts[parts.length - 1][0]}.`;
}

/** Facts are generated by code from verified extractions only — no model can embellish them. */
export function factsFrom(est: Extraction, providerName: string, docs: Doc[], cur: string): string[] {
  const f: string[] = [];
  const who = displayName(est.patientName);
  f.push(`${providerName} estimates ${fmtMoney(est.total ?? 0, cur)} as the family's share for ${est.procedure ? est.procedure.charAt(0).toLowerCase() + est.procedure.slice(1) : "treatment"}${est.insuranceCovered ? `, after the insurer pre-authorised ${fmtMoney(est.insuranceCovered, cur)}` : ""}.`);
  if (est.diagnosis) f.push(`Diagnosis on the hospital documents: ${est.diagnosis}.`);
  if (est.patientAge != null) f.push(`${who} is ${est.patientAge} years old, consistent across ${docs.filter((d) => d.extraction?.patientName).length} documents.`);
  if (est.documentDate) f.push(`The estimate was issued on ${est.documentDate}${est.documentNumber ? ` (ref. ${est.documentNumber})` : ""}.`);
  f.push(`Money raised can only be paid to ${providerName}'s registered PayPal account against the final bill, plus up to 10% for verified pharmacy receipts paid to the pharmacy.`);
  return f;
}

// ─── Create & verify ───────────────────────────────────────────────

export interface NewCampaign {
  organizer: { name: string; email: string; relationship: string };
  providerId: string;
  title: string;
  story: string;
  currency?: string;
  space?: string;
  files: { kind: DocKind; filename: string; buf: Buffer; fallback?: Extraction }[];
  lab?: boolean;
}

export async function createCampaign(input: NewCampaign): Promise<Campaign> {
  const p = needProvider(input.providerId);
  if (!isCampaignPayee(p)) throw new HttpError(400, "Campaigns raise money for a hospital or clinic");
  if (!input.files.some((f) => f.kind === "estimate")) throw new HttpError(400, "Upload the hospital's cost estimate");
  const docs = await Promise.all(input.files.map((f) => ingest(f.kind, f.filename, f.buf, "organizer")));
  input.files.forEach((f, i) => f.fallback && labFallbacks.set(docs[i].id, f.fallback));
  const c: Campaign = {
    id: uid("cmp"),
    space: input.space ?? "main",
    createdAt: nowIso(),
    status: "verifying",
    currency: input.currency ?? "USD",
    organizer: input.organizer,
    providerId: p.id,
    patient: { displayName: "The patient", age: null },
    title: input.title.trim() || "Help with hospital costs",
    story: input.story.trim(),
    facts: [],
    goal: "0.00",
    docs,
    donations: [],
    careCosts: [],
    movements: [],
    events: [],
    ...(input.lab ? { lab: true } : {}),
  };
  addEvent(c, { actor: "organizer", kind: "campaign.created", message: `${input.organizer.name} started the campaign and uploaded ${docs.length} document${docs.length > 1 ? "s" : ""}.` });
  await saveCampaign(c);
  return verify(c.id);
}

export async function verify(id: string): Promise<Campaign> {
  const c0 = await getCampaign(id);
  if (!c0) throw new HttpError(404, "Campaign not found");
  const p = needProvider(c0.providerId);
  let docs: Doc[];
  try {
    docs = await Promise.all(c0.docs.map((d) => (d.extraction ? d : read(d))));
  } catch (e) {
    await updateCampaign(id, (c) => {
      c.status = "needs_review";
      addEvent(c, { actor: "system", kind: "verify.error", message: `Documents couldn't be read automatically, so a person will review them: ${(e as Error).message}` });
    });
    throw e;
  }
  const report = verifyCampaign({ campaignId: id, docs, provider: p, prior: await priorDocs(spaceOf(c0)) });
  report.notes = await investigatorNotes(report.checks, `Campaign for a patient at ${p.name}. Verdict: ${report.decision} (${report.risk} risk).`);
  const est = docs.find((d) => d.kind === "estimate")?.extraction;
  const updated = await updateCampaign(id, (c) => {
    c.docs = docs;
    c.verification = report;
    if (est) {
      c.patient = { displayName: displayName(est.patientName), age: est.patientAge };
      c.currency = est.currency || c.currency;
    }
    c.goal = report.verifiedGoal.toFixed(2);
    c.facts = est && report.decision === "verified" ? factsFrom(est, p.name, docs, c.currency) : [];
    c.status = report.decision === "verified" ? "live" : "needs_review";
    const model = docs.find((d) => d.readerModel)?.readerModel ?? "the reader";
    const fails = report.checks.filter((k) => k.status === "fail").length;
    addEvent(c, {
      actor: "ai",
      kind: `verify.${report.decision}`,
      message:
        report.decision === "verified"
          ? `Verified: ${report.checks.length} checks on ${docs.length} documents (read by ${model}). Goal set to ${fmtMoney(c.goal, c.currency)}. The campaign is live.`
          : fails
            ? `On hold: ${fails} check${fails > 1 ? "s" : ""} failed (${report.risk} risk). Nobody can donate until a person reviews it. The family can respond.`
            : `Held for a quick human review: ${report.summary}`,
    });
    return structuredClone(c);
  });
  await remember(updated, docs);
  const refs = report.checks.find((k) => k.id === "duplicate")?.refs ?? [];
  if (refs.length) await alertOriginals(updated, refs);
  return updated;
}

// ─── Family response & reviewer ───────────────────────────────────

export async function organizerRespond(id: string, text: string) {
  return updateCampaign(id, (c) => {
    expect(c, "needs_review", "bill_needs_review");
    c.organizerResponse = { text: text.trim().slice(0, 2000), at: nowIso() };
    addEvent(c, { actor: "organizer", kind: "review.response", message: `${c.organizer.name} responded to the review: “${text.trim().slice(0, 220)}”` });
    return c;
  });
}

export async function reviewerDecideCampaign(id: string, approve: boolean, note: string) {
  return updateCampaign(id, (c) => {
    expect(c, "needs_review");
    c.status = approve ? "live" : "rejected";
    c.reviewerNote = note;
    if (approve && !c.facts.length) {
      const est = c.docs.find((d) => d.kind === "estimate")?.extraction;
      if (est) c.facts = factsFrom({ ...est, total: Number(c.goal) }, needProvider(c.providerId).name, c.docs, c.currency);
    }
    addEvent(c, {
      actor: "reviewer",
      kind: approve ? "review.approved" : "review.rejected",
      message: approve
        ? `A reviewer approved the campaign with a goal of ${fmtMoney(c.goal, c.currency)}${note ? `: ${note}` : "."}`
        : `A reviewer rejected the campaign${note ? `: ${note}` : "."} No donor was or will be charged.`,
    });
    return c;
  });
}

// ─── Donations (PayPal holds) ─────────────────────────────────────

export type PledgeInput = {
  donorName: string;
  donorEmail: string;
  amount: string;
  anonymous: boolean;
  message: string;
  surplus?: "release" | "offer";
  /** Accepting a "pass it on" offer from another campaign's receipt. */
  fromOffer?: { campaignId: string; donationId: string };
  /** Also save the donor's PayPal for their Giving Agent (the first gift of a mandate). */
  vault?: boolean;
  /** Where PayPal sends the donor after approving (redirect flow, e.g. a pledge started by an AI
   *  assistant over MCP). PayPal appends ?token=<orderId>. Defaults to the campaign page. */
  returnPath?: string;
};

/** How much more this campaign may take in pledges, in cents. */
async function roomFor(c: Campaign, reserved = 0): Promise<number> {
  const pledged = c.donations.filter((x) => x.status === "held").reduce((s, x) => s + toCents(x.pledged), 0);
  // Open offers from other receipts keep their place; an accepted offer uses its own place.
  const offered = offeredCents(c.id, await listCampaigns([spaceOf(c)]));
  // Pledges close once the goal is reached; the pledge that crosses it may overshoot by up to
  // 10%, a buffer for holds that later lapse.
  return pledged >= toCents(c.goal) && !reserved ? 0 : Math.floor(toCents(c.goal) * MAX_OVERPLEDGE) - pledged - offered + reserved;
}

export async function createDonationOrder(id: string, d: PledgeInput) {
  const c = await getCampaign(id);
  if (!c) throw new HttpError(404, "Campaign not found");
  expect(c, "live");
  const cents = toCents(d.amount);
  if (cents < 100) throw new HttpError(400, "The minimum donation is 1.00");
  let forwardedFrom: Donation["forwardedFrom"];
  let reserved = 0;
  if (d.fromOffer) {
    const src = await getCampaign(d.fromOffer.campaignId);
    const sd = src?.donations.find((x) => x.id === d.fromOffer!.donationId);
    if (!src || !sd || !offerOpen(sd.offer) || sd.offer.campaignId !== c.id) throw new HttpError(409, "That offer has expired or was already used. You can still pledge here as a new gift.");
    if (cents > toCents(sd.offer.amount)) throw new HttpError(400, `This offer is for up to ${fmtMoney(sd.offer.amount, c.currency)}.`);
    forwardedFrom = { campaignId: src.id, donationId: sd.id, patient: src.patient.displayName };
    reserved = toCents(sd.offer.amount);
  }
  const room = await roomFor(c, reserved);
  if (room <= 0) throw new HttpError(409, "This campaign is fully pledged. Thank you! Another verified patient may still need help.");
  if (cents > room) throw new HttpError(409, `This campaign can use at most ${fmtMoney(fromCents(room), c.currency)} more.`);
  const donation: Donation = {
    id: uid("don"),
    donorName: d.donorName.trim() || "A friend",
    donorEmail: d.donorEmail.trim(),
    anonymous: d.anonymous,
    message: d.message.trim().slice(0, 280),
    pledged: fromCents(cents),
    status: "pending",
    createdAt: nowIso(),
    surplus: d.surplus === "offer" ? "offer" : "release",
    ...(forwardedFrom ? { forwardedFrom } : {}),
  };
  const base = appBaseUrl();
  const order = await paypal.createAuthorizeOrder({
    amount: donation.pledged,
    currency: c.currency,
    description: `Earmark hold for ${c.patient.displayName}'s hospital bill`,
    customId: `${c.id}:${donation.id}`,
    invoiceId: `${donation.id}`,
    returnUrl: `${base}${d.returnPath ?? `/c/${c.id}`}`,
    cancelUrl: `${base}/c/${c.id}`,
    payeeEmail: paypal.payeeMode() === "direct" ? needProvider(c.providerId).paypalEmail : undefined,
    vault: d.vault,
  });
  donation.orderId = order.id;
  await updateCampaign(id, (cc) => {
    cc.donations.push(donation);
  });
  return { orderId: order.id, donationId: donation.id, approveUrl: order.approveUrl };
}

export async function confirmDonation(id: string, donationId: string, orderId: string, opts: { onAuthorized?: (auth: paypal.AuthorizationResult) => Promise<void> | void } = {}) {
  const c = await getCampaign(id);
  if (!c) throw new HttpError(404, "Campaign not found");
  const d0 = c.donations.find((x) => x.id === donationId);
  if (!d0) throw new HttpError(404, "Donation not found");
  if (d0.status === "held") return c;
  if (d0.orderId !== orderId) throw new HttpError(400, "Order doesn't belong to this donation");
  const auth = await paypal.authorizeOrder(orderId);
  await opts.onAuthorized?.(auth);
  const out = await updateCampaign(id, (cc) => {
    const d = cc.donations.find((x) => x.id === donationId)!;
    d.status = "held";
    d.authorizationId = auth.authorizationId;
    d.authorizationExpiresAt = auth.expiresAt;
    d.authorizedAt = nowIso();
    cc.movements.push({ id: uid("mv"), type: "hold", amount: d.pledged, currency: cc.currency, paypalId: auth.authorizationId, status: auth.status, donationId: d.id, at: nowIso(), note: d.forwardedFrom ? `New hold, passed on from ${d.forwardedFrom.patient}'s campaign` : "Held on the donor's PayPal, not charged" });
    const who = d.anonymous ? "An anonymous donor" : d.donorName;
    addEvent(cc, {
      actor: "paypal",
      kind: "donation.held",
      message: d.forwardedFrom
        ? `${who} passed on ${fmtMoney(d.pledged, cc.currency)} that ${d.forwardedFrom.patient}'s bill didn't need. It's a new PayPal hold, approved by the donor, not charged yet.`
        : `${who} pledged ${fmtMoney(d.pledged, cc.currency)}. It's held on their PayPal, not charged.`,
    });
    return structuredClone(cc);
  });
  const fwd = out.donations.find((x) => x.id === donationId)?.forwardedFrom;
  if (fwd) {
    await updateCampaign(fwd.campaignId, (src) => {
      const sd = src.donations.find((x) => x.id === fwd.donationId);
      if (sd?.offer) {
        sd.offer.status = "accepted";
        sd.offer.acceptedDonationId = donationId;
      }
    }).catch(() => undefined);
  }
  return out;
}

/** The donor said "No thanks" to the offer on their receipt. Nothing is charged either way. */
export async function declineOffer(id: string, donationId: string) {
  return updateCampaign(id, (c) => {
    const d = c.donations.find((x) => x.id === donationId);
    if (!d?.offer) throw new HttpError(404, "No offer on this pledge");
    if (d.offer.status === "open") d.offer.status = "declined";
    return c;
  });
}

/** Another verified patient a donor could help instead, e.g. when this campaign is fully pledged. */
export async function nextPatientFor(c: Campaign) {
  const all = await listCampaigns([spaceOf(c)]);
  const n = nextPatients(c, all)[0];
  return n ? { id: n.c.id, title: n.c.title, patient: n.c.patient.displayName, hospital: getProvider(n.c.providerId)?.name ?? "", needs: fromCents(n.needs) } : null;
}

/** After settlement: donors who chose "offer me another patient" get one offer each, on their
 *  receipt, for at most what the bill didn't need and at most what the other patient still needs. */
async function makeOffers(id: string) {
  const c = await getCampaign(id);
  if (!c) return;
  const wanting = c.donations.filter((d) => d.surplus === "offer" && !d.offer && (d.status === "captured" || d.status === "voided") && toCents(d.neverCharged ?? "0") >= MIN_OFFER_CENTS);
  if (!wanting.length) return;
  const all = await listCampaigns([spaceOf(c)]);
  const targets = nextPatients(c, all);
  if (!targets.length) return;
  const plan = planOffers(wanting.map((d) => ({ id: d.id, neverChargedCents: toCents(d.neverCharged ?? "0") })), targets.map((t) => ({ id: t.c.id, needsCents: t.needs })));
  if (!plan.length) return;
  const expiresAt = new Date(Date.now() + OFFER_DAYS * 864e5).toISOString();
  await updateCampaign(id, (cc) => {
    for (const p of plan) {
      const t = targets.find((x) => x.c.id === p.targetId)!.c;
      const d = cc.donations.find((x) => x.id === p.donorId)!;
      d.offer = { campaignId: t.id, patient: t.patient.displayName, hospital: getProvider(t.providerId)?.name ?? "", amount: fromCents(p.amountCents), needs: fromCents(p.needsCents), expiresAt, status: "open", at: nowIso() };
    }
    const names = [...new Set(plan.map((p) => targets.find((x) => x.c.id === p.targetId)!.c.patient.displayName))].join(" and ");
    addEvent(cc, { actor: "system", kind: "offers.made", message: `${plan.length} donor${plan.length > 1 ? "s" : ""} asked to be offered another patient with what the bill didn't need. Their receipts now offer ${names}, as a new PayPal hold they approve themselves. Nothing was charged; Earmark holds nothing.` });
  });
}

