const samples = path.join(process.cwd(), "public", "samples");

/** Create any catalog campaign that doesn't exist yet. Safe to call repeatedly. */
export async function ensureCatalog(): Promise<void> {
  const existing = await listCampaigns([CATALOG_SPACE]);
  for (const f of FAMILIES) {
    if (existing.some((c) => c.docs.some((d) => d.filename === `${f.slug}-estimate.png`))) continue;
    await createCampaign({
      space: CATALOG_SPACE,
      organizer: f.organizer,
      providerId: f.providerId,
      title: f.title,
      story: f.story,
      files: [
        { kind: "estimate", filename: `${f.slug}-estimate.png`, buf: await fs.readFile(path.join(samples, `${f.slug}-estimate.png`)) },
        { kind: "identity", filename: `${f.slug}-registration.png`, buf: await fs.readFile(path.join(samples, `${f.slug}-registration.png`)) },
      ],
    });
  }
}

export type CatalogEntry = {
  id: string;
  title: string;
  patient: string;
  age: number | null;
  hospital: string;
  city: string;
  procedure: string;
  diagnosis: string;
  goal: string;
  held: string;
  stillNeeds: string;
  donors: number;
  checksPassed: number;
  checksTotal: number;
  checksFailed: number;
  url: string;
};

/** Live, verified catalog campaigns, with the evidence summary an agent (or a person) needs. */
export async function catalog(baseUrl = ""): Promise<CatalogEntry[]> {
  const cs = (await listCampaigns([CATALOG_SPACE])).filter((c) => c.status === "live");
  return cs.map((c) => summarize(c, baseUrl));
}

export function summarize(c: Campaign, baseUrl = ""): CatalogEntry {
  const est = c.docs.find((d) => d.kind === "estimate")?.extraction;
  const held = c.donations.filter((d) => d.status === "held").reduce((s, d) => s + toCents(d.pledged), 0);
  const goal = toCents(c.goal);
  const checks = c.verification?.checks ?? [];
  return {
    id: c.id,
    title: c.title,
    patient: c.patient.displayName,
    age: c.patient.age,
    hospital: provider(c.providerId)?.name ?? "",
    city: provider(c.providerId)?.city ?? "",
    procedure: est?.procedure ?? "",
    diagnosis: est?.diagnosis ?? "",
    goal: (goal / 100).toFixed(2),
    held: (held / 100).toFixed(2),
    stillNeeds: (Math.max(0, goal - held) / 100).toFixed(2),
    donors: c.donations.filter((d) => d.status === "held").length,
    checksPassed: checks.filter((k) => k.status === "pass").length,
    checksTotal: checks.length,
    checksFailed: checks.filter((k) => k.status === "fail").length,
    url: `${baseUrl}/c/${c.id}`,
  };
}
